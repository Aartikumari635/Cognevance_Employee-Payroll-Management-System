    private void btnsaveActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnsaveActionPerformed
        // TODO add your handling code here:
                                            

    String id = txtempid.getText();

    if (id.isEmpty() || txtnet.getText().isEmpty()) {
        JOptionPane.showMessageDialog(this,
                "Please enter Employee ID and calculate salary first");
        return;
    }

    try {
        double basic = Double.parseDouble(txtsal.getText());
        double allowance = Double.parseDouble(txtallowance.getText());
        double deduction = Double.parseDouble(txtdeduction.getText());
        double net = Double.parseDouble(txtnet.getText());

        Connection con = Connect.Connection();

        String sql = "UPDATE employee SET allowance=?, deduction=?, net_salary=? WHERE id=?";

        PreparedStatement pst = con.prepareStatement(sql);

        pst.setDouble(1, allowance);
        pst.setDouble(2, deduction);
        pst.setDouble(3, net);
        pst.setString(4, id);

        int result = pst.executeUpdate();

        if (result > 0) {
            JOptionPane.showMessageDialog(this,
                    "Payroll Saved Successfully!");
        } else {
            JOptionPane.showMessageDialog(this,
                    "Employee ID not found. Please search first.");
        }

        pst.close();
        con.close();

    } catch (NumberFormatException e) {
        JOptionPane.showMessageDialog(this,
                "Please enter valid salary values");

    } catch (SQLException e) {
        JOptionPane.showMessageDialog(this,
                "Database Error: " + e.getMessage());
    }

    }//GEN-LAST:event_btnsaveActionPerformed

