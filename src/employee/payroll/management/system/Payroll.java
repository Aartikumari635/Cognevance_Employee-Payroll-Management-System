    private void btncalculateActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btncalculateActionPerformed
        // TODO add your handling code here:
       
    try {
        double basic = Double.parseDouble(txtsal.getText());
        double allowance = Double.parseDouble(txtallowance.getText());
        double deduction = Double.parseDouble(txtdeduction.getText());

        if (basic < 0 || allowance < 0 || deduction < 0) {
            JOptionPane.showMessageDialog(this, "Salary values cannot be negative");
            return;
        }

        double netSalary = basic + allowance - deduction;

        txtnet.setText(String.valueOf(netSalary));

    } catch (NumberFormatException e) {
        JOptionPane.showMessageDialog(this,
                "Please enter valid Basic Salary, Allowance and Deduction");
    }

    }//GEN-LAST:event_btncalculateActionPerformed

